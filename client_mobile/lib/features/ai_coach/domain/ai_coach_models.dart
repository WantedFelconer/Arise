/// Represents a message in an AI Coach conversation.
class AiCoachMessage {
  final String id;
  final String conversationId;
  final String role; // 'user' | 'assistant' | 'system'
  final String content;
  final DateTime createdAt;
  final List<dynamic> toolCalls;
  final bool isOptimistic;

  const AiCoachMessage({
    required this.id,
    this.conversationId = '',
    required this.role,
    required this.content,
    required this.createdAt,
    this.toolCalls = const [],
    this.isOptimistic = false,
  });

  bool get isUser => role == 'user';
  bool get isAssistant => role == 'assistant' || role == 'system';

  factory AiCoachMessage.fromJson(Map<String, dynamic> json) {
    return AiCoachMessage(
      id: json['id'] as String? ?? '',
      conversationId: json['conversationId'] as String? ?? '',
      role: json['role'] as String? ?? 'assistant',
      content: json['content'] as String? ?? '',
      createdAt: json['createdAt'] != null
          ? DateTime.tryParse(json['createdAt'] as String) ?? DateTime.now()
          : DateTime.now(),
      toolCalls: json['toolCalls'] as List<dynamic>? ?? [],
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'conversationId': conversationId,
      'role': role,
      'content': content,
      'createdAt': createdAt.toIso8601String(),
      'toolCalls': toolCalls,
    };
  }
}

/// Represents the authoritative backend AI quota status.
/// Section 10.5: Quota resets at UTC midnight.
class AiQuota {
  final int usedToday;
  final int dailyLimit;
  final int remaining;
  final DateTime resetAt;

  const AiQuota({
    required this.usedToday,
    required this.dailyLimit,
    required this.remaining,
    required this.resetAt,
  });

  bool get isExhausted => remaining <= 0;

  factory AiQuota.fromJson(Map<String, dynamic> json) {
    final rawData = json['data'] is Map<String, dynamic>
        ? json['data'] as Map<String, dynamic>
        : json;

    final limit = (rawData['dailyLimit'] as num?)?.toInt() ??
        (rawData['limit'] as num?)?.toInt() ??
        50;
    final used = (rawData['usedToday'] as num?)?.toInt() ?? 0;
    final rem = (rawData['remaining'] as num?)?.toInt() ?? (limit - used).clamp(0, limit);

    DateTime reset;
    if (rawData['resetAt'] != null) {
      reset = DateTime.tryParse(rawData['resetAt'] as String) ?? _defaultReset();
    } else {
      reset = _defaultReset();
    }

    return AiQuota(
      usedToday: used,
      dailyLimit: limit,
      remaining: rem,
      resetAt: reset,
    );
  }

  static DateTime _defaultReset() {
    final now = DateTime.now().toUtc();
    return DateTime.utc(now.year, now.month, now.day + 1);
  }

  Map<String, dynamic> toJson() {
    return {
      'usedToday': usedToday,
      'dailyLimit': dailyLimit,
      'remaining': remaining,
      'resetAt': resetAt.toIso8601String(),
    };
  }
}

/// Proactive AI Coach nudge.
