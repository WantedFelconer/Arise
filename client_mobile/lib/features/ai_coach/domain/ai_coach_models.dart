  final String type; // 'overload' | 'procrastination' | 'boss_momentum' | 'streak_risk'
  final String title;
  final String message;
  final String? actionTarget;
  final String priority;

  const AiCoachNudge({
    required this.type,
    required this.title,
    required this.message,
    this.actionTarget,
    this.priority = 'normal',
  });

  factory AiCoachNudge.fromJson(Map<String, dynamic> json) {
    return AiCoachNudge(
      type: json['type'] as String? ?? 'general',
      title: json['title'] as String? ?? '',
      message: json['message'] as String? ?? '',
      actionTarget: json['actionTarget'] as String?,
      priority: json['priority'] as String? ?? 'normal',
    );
  }
}

/// Daily schedule proposal generated by AI Coach.
class DailyPlanProposal {
  final String date;
  final String summary;
  final List<String> schedule;
  final int targetXp;
  final int energyBudget;

  const DailyPlanProposal({
    required this.date,
    required this.summary,
    this.schedule = const [],
    this.targetXp = 0,
    this.energyBudget = 100,
  });

  factory DailyPlanProposal.fromJson(Map<String, dynamic> json) {
    final raw = json['data'] is Map<String, dynamic> ? json['data'] as Map<String, dynamic> : json;
    return DailyPlanProposal(
      date: raw['date'] as String? ?? '',
      summary: raw['summary'] as String? ?? raw['text'] as String? ?? '',
      schedule: (raw['schedule'] as List<dynamic>?)?.map((s) => s.toString()).toList() ?? [],
      targetXp: (raw['targetXp'] as num?)?.toInt() ?? 0,
      energyBudget: (raw['energyBudget'] as num?)?.toInt() ?? 100,
    );
  }
}

/// Weekly review summary synthesized by AI Coach.
class WeeklyReviewSummary {
  final String summary;
  final int completionRatePct;
  final int xpEarned;
  final int focusMinutes;
  final String reflection;

  const WeeklyReviewSummary({
    required this.summary,
    this.completionRatePct = 0,
    this.xpEarned = 0,
    this.focusMinutes = 0,
    required this.reflection,
  });

  factory WeeklyReviewSummary.fromJson(Map<String, dynamic> json) {
    final raw = json['data'] is Map<String, dynamic> ? json['data'] as Map<String, dynamic> : json;
    return WeeklyReviewSummary(
      summary: raw['summary'] as String? ?? raw['text'] as String? ?? '',
      completionRatePct: (raw['completionRatePct'] as num?)?.toInt() ?? 0,
      xpEarned: (raw['xpEarned'] as num?)?.toInt() ?? 0,
      focusMinutes: (raw['focusMinutes'] as num?)?.toInt() ?? 0,
      reflection: raw['reflection'] as String? ?? '',
    );
  }
}
